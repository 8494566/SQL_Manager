"""Generate the item-set data module from the legacy C++ source.

The legacy tool (`MFCAppManagerDlg.cpp`) embeds one huge hardcoded ``0x...``
``GoodsBuf`` blob per class/container preset inside each button handler. Those
lines are far too long to hand-copy, so this script extracts them verbatim and
emits ``sqlmanager/assets/itemsets_data.py``.

Run:  python tools/extract_itemsets.py
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "MFCAppManager" / "MFCAppManagerDlg.cpp"
OUTPUT = ROOT / "sqlmanager" / "assets" / "itemsets_data.py"

# handler function name -> (preset key, human label)
HANDLERS = {
    "OnBnClickedButton4Zs": ("4zs", "4职业-战士"),
    "OnBnClickedButton4Hy": ("4hy", "4职业-游侠"),
    "OnBnClickedButton4Fs": ("4fs", "4职业-法师"),
    "OnBnClickedButton5Noe": ("5noe", "5职业-一"),
    "OnBnClickedButton5Two": ("5two", "5职业-二"),
    "OnBnClickedButton2Hy": ("2hy", "2职业-游侠"),
    "OnBnClickedButton2Zs": ("2zs", "2职业-战士"),
    "OnBnClickedButton2Fs": ("2fs", "2职业-法师"),
}

HANDLER_RE = re.compile(r"::(OnBnClickedButton\w+)\s*\(")
# VALUES('<container>','%d',0x<HEX>[,'<num>']) - hex is greedy up to the tail.
INSERT_RE = re.compile(
    r"INSERT\s+INTO\s+dbo\.Goods.*?VALUES\(\s*\\?'(\d+)\\?'\s*,\s*\\?'%d\\?'\s*,\s*"
    r"0x([0-9A-Fa-f]+)\s*(?:,\s*\\?'?(\d+)\\?'?\s*)?\)",
    re.IGNORECASE,
)


def extract() -> dict[str, dict]:
    text = SOURCE.read_text(encoding="utf-8", errors="replace")
    # Split into per-function blocks keyed by handler name.
    presets: dict[str, dict] = {}
    positions = [(m.group(1), m.start()) for m in HANDLER_RE.finditer(text)]
    for i, (name, start) in enumerate(positions):
        if name not in HANDLERS:
            continue
        end = positions[i + 1][1] if i + 1 < len(positions) else len(text)
        block = text[start:end]
        m = INSERT_RE.search(block)
        if not m:
            print(f"WARN: no INSERT blob found in {name}")
            continue
        container = int(m.group(1))
        hex_blob = m.group(2)
        goods_num = int(m.group(3)) if m.group(3) is not None else 0
        if len(hex_blob) % 2 != 0:
            raise ValueError(f"{name}: odd-length hex blob ({len(hex_blob)})")
        key, label = HANDLERS[name]
        presets[key] = {
            "label": label,
            "container": container,
            "goods_num": goods_num,
            "hex": hex_blob.upper(),
        }
        print(f"OK  {key:5} label={label} container={container} "
              f"bytes={len(hex_blob)//2} goods_num={goods_num}")
    return presets


def render(presets: dict[str, dict]) -> str:
    lines = [
        '"""Item-set blobs extracted verbatim from the legacy MFC source.',
        "",
        "GENERATED by tools/extract_itemsets.py - do not edit by hand.",
        '"""',
        "",
        "# preset key -> {label, container, goods_num, buf(bytes)}",
        "ITEM_SETS = {",
    ]
    for key, p in presets.items():
        lines.append(f"    {key!r}: {{")
        lines.append(f"        \"label\": {p['label']!r},")
        lines.append(f"        \"container\": {p['container']},")
        lines.append(f"        \"goods_num\": {p['goods_num']},")
        lines.append(f"        \"buf\": bytes.fromhex({p['hex']!r}),")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(f"legacy source not found: {SOURCE}")
    presets = extract()
    if not presets:
        raise SystemExit("no presets extracted - check the regexes")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(presets), encoding="utf-8")
    print(f"\nwrote {OUTPUT} ({len(presets)} presets)")


if __name__ == "__main__":
    main()
